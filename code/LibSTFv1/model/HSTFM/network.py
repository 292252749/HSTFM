class HSTFM(nn.Module):
    def __init__(self, in_channels=4, dim=96, window_size=16, img_size=512, cf_ratio=8):
        super().__init__()
        self.cf_ratio = cf_ratio
        self.window_size = window_size
        self.dim = dim
        self.overlap_ratio = 0.5 

        # 0. 注册 Buffer (归一化参数)
        self.register_buffer('mu_a', torch.tensor([69.7858, 63.2584, 56.0688, 56.8054]).view(1, -1, 1, 1))
        self.register_buffer('std_a', torch.tensor([36.3890, 34.8867, 36.1350, 23.1515]).view(1, -1, 1, 1))
        self.register_buffer('mu_A', torch.tensor([0.2160, 0.2445, 0.2657, 0.3699]).view(1, -1, 1, 1))
        self.register_buffer('std_A', torch.tensor([0.1540, 0.1517, 0.1603, 0.1290]).view(1, -1, 1, 1))

        # 1. 浅层特征提取
        self.conv_input_c = nn.Conv2d(in_channels, dim//2, 3, 1, 1)
        self.conv_input_c_mask = nn.Conv2d(in_channels + 1, dim//2, 3, 1, 1)
        self.conv_down_a_8 = nn.Conv2d(in_channels, dim//2, 3, 1, 1)
        self.avgpool_8 = nn.AvgPool2d(kernel_size=8, stride=8)

        # 2. 对齐模块 (SiameseEDA)
        # 假设 SiameseEDA 已经正确定义并引入
        self.align = SiameseEDA(in_channels=dim//2)

        # 3. 金字塔编码 (用于 A)
        self.pyramid_enc_A = PyramidEncoder(in_channels, dim)

        # 4. HAT 索引 Buffer (关键修复：注册不同尺寸的 RPI)
        # 标准窗口 (Stage 2, 3, 4)
