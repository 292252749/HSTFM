# 2. 主 EDA 结构 (Siamese EDA)
#    - 职责：层级编解码，管理 Offset 传递
# =========================================================================
class SiameseEDA(pl.LightningModule):
    def __init__(self, in_channels=64):
        super(SiameseEDA, self).__init__()
        dim = in_channels
        # === Encoder ===
        # L1: [B, C, H, W]
        self.enc_l1 = nn.Sequential(BFA(dim), BFA(dim))
        self.down1 = nn.Conv2d(dim, dim, 3, 2, 1)
        
        # L2: [B, C, H/2, W/2]
        self.enc_l2 = nn.Sequential(BFA(dim), BFA(dim))
        self.down2 = nn.Conv2d(dim, dim, 3, 2, 1) # 只有当有L3时才用，当前只用了L1, L2
        
        # === Alignment ===
        self.align_l2 = AlignmentBlock(dim)
        self.align_l1 = AlignmentBlock(dim)
        
        # Context Upsampler (用于把 L2 的 offset 特征传给 L1)
        self.context_up = nn.ConvTranspose2d(dim, dim, 3, 2, 1, output_padding=1)

        # === Decoder ===
        # 1. 把 L2 上采样回 L1 的尺寸
        self.up2 = nn.ConvTranspose2d(dim, dim, 3, 2, 1, output_padding=1)
        
        # 2. L1 层的融合 (Concat 后降维)
        self.fusion2 = nn.Conv2d(dim*2, dim, 3, 1, 1) 
        
        # 3. [修复点] L1 层的后续处理 (不再上采样，保持原分辨率)
        # 原来的 up1 删掉，改为普通卷积
        self.refine_l1 = nn.Sequential(
            nn.Conv2d(dim, dim, 3, 1, 1, bias=False),
            nn.GELU()
        )
        
    def extract_pyramid(self, x):
        """提取特征金字塔: [L1, L2]"""
        f1 = self.enc_l1(x)       # Size: (H, W)
        f2 = self.down1(f1)
        f2 = self.enc_l2(f2)      # Size: (H/2, W/2)
        # f_bot = self.down2(f2)  # 暂时不用更深层，只演示2层结构
        return f1, f2

    def process_stream(self, x_feats, ref_feats=None, saved_params=None):
        f1, f2 = x_feats
        r1, r2 = ref_feats if ref_feats else (None, None)
        
        p_l2 = saved_params['l2'] if saved_params else None
        p_l1 = saved_params['l1'] if saved_params else None
        new_params = {}

        # --- 1. Level 2 (Low Res) 对齐 ---
        f2_aligned, context_l2, params_l2 = self.align_l2(
            f2, r2, prev_context=None, external_params=p_l2
        )
        if saved_params is None: new_params['l2'] = params_l2
        
        # --- 2. Level 1 (High Res) 对齐 ---
        # 将 L2 的 Context 上采样，作为 L1 的引导
        context_l2_up = self.context_up(context_l2)
        
        f1_aligned, _, params_l1 = self.align_l1(
            f1, r1, prev_context=context_l2_up, external_params=p_l1
        )
        if saved_params is None: new_params['l1'] = params_l1
        
        # --- 3. Decoder 重建 ---
        # Upsample aligned L2 to (H, W)
        dec = self.up2(f2_aligned) 
        
        # Fuse with aligned L1 (H, W)
        dec = torch.cat([dec, f1_aligned], dim=1)
        dec = self.fusion2(dec) + f1_aligned # Residual
        
        # [修复点] 最后的处理，不改变尺寸
        dec = self.refine_l1(dec)
        
        return dec, new_params

    def forward(self, a, b, A):
        # 1. 提取
        pyr_a = self.extract_pyramid(a)
        pyr_b = self.extract_pyramid(b)
        pyr_A = self.extract_pyramid(A)
        
        # 2. Master (a -> A)
        feat_out_a, params = self.process_stream(pyr_a, ref_feats=pyr_A, saved_params=None)
        
        # 3. Slave (b -> ?)
        feat_out_b, _ = self.process_stream(pyr_b, ref_feats=None, saved_params=params)
        
        return feat_out_a, feat_out_b

        
class DWResBlock(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.body = nn.Sequential(
            # Depthwise
            nn.Conv2d(dim, dim, 3, 1, 1, groups=dim), 
            nn.Conv2d(dim, dim, 1), # Pointwise
            nn.LeakyReLU(0.1, True),
            # Depthwise
            nn.Conv2d(dim, dim, 3, 1, 1, groups=dim),
            nn.Conv2d(dim, dim, 1)  # Pointwise
        )
    def forward(self, x): return x + self.body(x)
    
class PyramidEncoder(nn.Module):
    """ CNN 金字塔编码器 """
    def __init__(self, in_channels, dim):
        super().__init__()
        self.enc0 = nn.Conv2d(in_channels, dim, 3, 1, 1)
        self.down1 = nn.Sequential(nn.Conv2d(dim, dim, 3, 2, 1), nn.LeakyReLU(0.1, True)) # H/2
        self.down2 = nn.Sequential(nn.Conv2d(dim, dim, 3, 2, 1), nn.LeakyReLU(0.1, True)) # H/4
        self.down3 = nn.Sequential(nn.Conv2d(dim, dim, 3, 2, 1), nn.LeakyReLU(0.1, True)) # H/8
        
    def forward(self, x):
        f0 = self.enc0(x)
        f1 = self.down1(f0)
        f2 = self.down2(f1)
        f3 = self.down3(f2)
        return [f0, f1, f2, f3]
         

