class BFA(pl.LightningModule):
    def __init__(self, dim, num_heads=2, stride=1, ffn_expansion_factor=2.5, bias=False, LayerNorm_type='WithBias'):
        super(BFA, self).__init__()

        self.norm1 = LayerNorm(dim, LayerNorm_type)
        self.attn = Attention(dim, num_heads, stride, bias)
        self.norm2 = LayerNorm(dim, LayerNorm_type)
        self.ffn = FeedForward(dim, ffn_expansion_factor, bias)

    def forward(self, x):
        x = x + self.attn(self.norm1(x))
        x = x + self.ffn(self.norm2(x))

        return x

# =========================================================================
# 1. 对齐模块 (Alignment Block)
#    - 职责：计算或复用 Offset，执行 DeformConv
#    - 改变：去掉了 BackProjection
# =========================================================================
class AlignmentBlock(nn.Module):
    def __init__(self, dim, kernel_size=7):
        super(AlignmentBlock, self).__init__()
        
        self.deform_groups = 8
        padding = kernel_size // 2
        
        # 1. 特征压缩/提取层 (用于生成 Context)
        # 输入: Source(dim) + Ref(dim) + Prev_Context(dim) = 3*dim
        self.context_conv = nn.Sequential(
            nn.Conv2d(dim * 3, dim, kernel_size=3, padding=1, bias=False),
            nn.GELU()
        )
        
        # 2. Offset 生成层
        # 输出: 2 * groups * k*k (offsets) + 1 * groups * k*k (masks)
        out_channels = self.deform_groups * 3 * (kernel_size**2)
        self.offset_conv = nn.Conv2d(dim, out_channels, kernel_size=kernel_size, padding=padding, bias=False)
        
        # 3. Deform Conv
        self.deform = DeformConv2d(dim, dim, kernel_size=kernel_size, padding=padding, groups=self.deform_groups)

    def forward(self, x, ref=None, prev_context=None, external_params=None):
        """
        x: 当前层级源特征 (a 或 b)
        ref: 当前层级参考特征 (A)，仅在 Master 模式下需要
        prev_context: 上一层的 Offset 特征 (上采样后)
        external_params: (offset, mask, current_context) -> Slave 模式下传入
        """
        
        # 初始化 prev_context (如果是最底层)
        if prev_context is None:
            prev_context = torch.zeros_like(x)

        if external_params is None:
            # === Master Mode (a -> A) ===
            # 计算 Context: 结合 Source, Ref 和 上下文
            # 注意: 这里必须有 ref
            combined = torch.cat([x, ref, prev_context], dim=1)
            current_context = self.context_conv(combined)
            
            # 生成 Offsets
            out = self.offset_conv(current_context)
            o1, o2, mask = torch.chunk(out, 3, dim=1)
            offset = torch.cat((o1, o2), dim=1)
            mask = torch.sigmoid(mask)
            
            params_to_save = (offset, mask, current_context)
            
        else:
            # === Slave Mode (b -> ?) ===
            # 完全复用 a 的参数
            offset, mask, current_context = external_params
            params_to_save = None # Slave 不需要保存给别人用

        # 执行对齐
        aligned_feat = self.deform(x, offset, mask)
        
        return aligned_feat, current_context, params_to_save

